//go:build ignore

// keysyms_gen writes keysyms_table.go: every character that libxkbcommon's
// xkb_utf32_to_keysym gives a legacy keysym instead of the Unicode keysym
// 0x01000000 + code point. Run it with `go generate ./internal/desktop` from
// host/; it needs libxkbcommon-devel, which gtk4-devel already pulls in.
package main

// #cgo pkg-config: xkbcommon
// #include <xkbcommon/xkbcommon.h>
import "C"

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"os/exec"
	"strings"
)

const unicodeOffset = 0x01000000

func main() {
	version, err := exec.Command("pkg-config", "--modversion", "xkbcommon").Output()
	if err != nil {
		log.Fatalf("read the libxkbcommon version: %v", err)
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by go run keysyms_gen.go; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package desktop\n\n")
	fmt.Fprintf(&b, "// legacyKeysyms holds the characters above Latin-1 that have a keysym of\n")
	fmt.Fprintf(&b, "// their own, as xkb_utf32_to_keysym of libxkbcommon %s picks it.\n", strings.TrimSpace(string(version)))
	fmt.Fprintf(&b, "var legacyKeysyms = map[rune]uint32{\n")
	n := 0
	for r := rune(0x100); r <= 0x10ffff; r++ {
		k := uint32(C.xkb_utf32_to_keysym(C.uint32_t(r)))
		if k == 0 || k == unicodeOffset+uint32(r) {
			continue
		}
		fmt.Fprintf(&b, "\t0x%04x: 0x%04x,\n", r, k)
		n++
	}
	fmt.Fprintf(&b, "}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatalf("format the table: %v", err)
	}
	if err := os.WriteFile("keysyms_table.go", src, 0o644); err != nil {
		log.Fatalf("write the table: %v", err)
	}
	log.Printf("wrote %d legacy keysyms", n)
}
